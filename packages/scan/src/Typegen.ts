import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { parseSync } from 'oxc-parser';
import { dirname, isAbsolute, join, relative, resolve } from 'pathe';
import { glob } from 'tinyglobby';
import { GLOB_SCAN_PATTERN } from './Scan';
import type { ScanLogger } from './Types';

/**
 * One route as the `routes` introspection section describes it. Declared here
 * structurally so the scanner does not depend on `@vercube/core`.
 */
export interface TypegenRoute {
  method: string;
  path: string;
  controller: string;
  handler: string;
  args: { idx: number; type: string; name?: string }[];
  sse?: boolean;
  /** An infrastructure route (health probes, devtools), always left out. */
  internal?: boolean;
  /**
   * Errors the route answers with: class name, status, and for an implicit
   * one (core adds a 400, 401 or 403 nobody declared) the module to import it from.
   */
  throws?: { name: string; status: number; module?: string }[];
}

/**
 * A type the generated file imports: `import type { name } from module`.
 * `module` is a package name or an absolute file path.
 */
export interface TypegenImport {
  module: string;
  name: string;
}

/** Errors `@vercube/core` exports, found there when a controller file does not say where one comes from. */
const CORE_ERRORS = new Set([
  'HttpError',
  'BadRequestError',
  'UnauthorizedError',
  'ForbiddenError',
  'NotFoundError',
  'MethodNotAllowedError',
  'NotAcceptableError',
  'PayloadTooLargeError',
  'UnsupportedMediaTypeError',
  'InternalServerError',
]);

/** What an error the generator cannot import is typed as. `RouteDef` adds the `status`. */
const UNKNOWN_ERROR = '{ name: string; message?: string }';

/** Where a controller class lives and how it is exported. */
export interface ControllerSource {
  /** Absolute path of the file. */
  file: string;
  /** The exported name, `default` for a default export, `null` when the class is not exported. */
  exportName: string | null;
  /**
   * Classes the file can name, by class name: what it imports and what it
   * exports itself. Used to import the errors its routes declare. `null` marks
   * a name the file knows but that cannot be imported: a class it does not
   * export, or two imports going by the same class name.
   */
  types?: Record<string, TypegenImport | null>;
}

/** Options for {@link generateRouteTypes}. */
export interface TypegenOptions {
  /** The routes to describe. */
  routes: TypegenRoute[];
  /**
   * Controller class name to its source. `null` marks a name declared in more
   * than one file, which cannot be told apart by name.
   */
  controllers: Record<string, ControllerSource | null>;
  /** Absolute path of the file the result is written to; imports are relative to it. */
  outFile: string;
  /** Module `RouteDef` is imported from. */
  clientModule?: string;
}

/** What {@link generateRouteTypes} produced. */
export interface TypegenResult {
  /** The declaration file. */
  code: string;
  /** Routes left out, with the reason, one per route id. */
  skipped: { id: string; reason: string }[];
  /** Absolute paths of the controller files the result imports. */
  files: string[];
  /** Problems that did not stop a route from being typed, such as an error class that could not be imported. */
  warnings: string[];
}

/** First line of every generated file, also how a generated file is recognised. */
export const TYPEGEN_HEADER = '// Generated by Vercube from your controllers. Do not edit: `vercube typegen` rewrites it.';

/** Files never worth parsing for controllers. */
const IGNORE = [
  '**/node_modules/**',
  '**/dist/**',
  '**/.output/**',
  '**/.vercube/**',
  '**/.nitro/**',
  '**/coverage/**',
  '**/*.d.ts',
  '**/*.{test,spec}.*',
  '**/{test,tests,__tests__}/**',
];

/** Names the generated file declares itself. */
const RESERVED = new Set(['RouteDef', 'VercubeRoutes']);

/** A `Controller(` call, allowing for whitespace and an alias such as `HttpController(`. */
const CONTROLLER_CALL = /Controller\s*\(|\bController\s+as\s/;

/** `:name` and `**:name` segments of a route template. */
const SEGMENT = /(?:\*\*)?:(\w+)/g;

/**
 * Picks the name each controller is imported as. The file's own names cannot be
 * taken, so `RouteDef` becomes `RouteDef_`, or `RouteDef__` when a controller
 * already has that name.
 *
 * @param controllers - Controller names from the route table
 * @returns The local name of each
 */
function localNames(controllers: string[]): Map<string, string> {
  const unique = [...new Set(controllers)];
  const taken = new Set(RESERVED);
  const locals = new Map<string, string>();

  // a name that is free keeps it; only the reserved ones move
  for (const name of [...unique.filter((n) => !RESERVED.has(n)), ...unique.filter((n) => RESERVED.has(n))]) {
    let local = name;

    while (taken.has(local)) {
      local += '_';
    }

    taken.add(local);
    locals.set(name, local);
  }

  return locals;
}

/**
 * Writes the type references `@vercube/client` turns into a typed route map.
 *
 * Nothing about the routes' types is printed: each entry names the controller
 * class, the handler and the argument index of each parameter decorator, and
 * `RouteDef` asks the compiler for the rest. Output is sorted, so the same
 * application always produces the same file.
 *
 * Routes whose controller cannot be imported (unknown file, not exported, the
 * class name declared twice) are left out and reported in `skipped`.
 *
 * @param options - Routes, controller sources and the output path
 * @returns The file and the routes it left out
 */
export function generateRouteTypes(options: TypegenOptions): TypegenResult {
  const { routes, controllers, outFile, clientModule = '@vercube/client' } = options;
  const entries = new Map<string, string>();
  const imports = new Map<string, Set<string>>();
  const files = new Set<string>();
  const skipped: TypegenResult['skipped'] = [];
  const warnings = new Set<string>();
  const names = new Set(routes.map((route) => route.controller));
  const locals = localNames([...names]);
  const taken = new Set([...RESERVED, ...locals.values()]);
  const typeLocals = new Map<string, string>();
  const addImport = (specifier: string, binding: string): void => {
    if (!imports.has(specifier)) {
      imports.set(specifier, new Set());
    }

    imports.get(specifier)!.add(binding);
  };

  // an error class, imported once under a name nothing else in the file has
  const importType = (type: TypegenImport, className: string): string => {
    const specifier = isAbsolute(type.module) ? toSpecifier(outFile, type.module) : type.module;
    const key = `${specifier}\0${type.name}`;
    let local = typeLocals.get(key);

    if (!local) {
      // a default export goes by its class name
      local = type.name === 'default' ? className : type.name;

      while (taken.has(local)) {
        local += '_';
      }

      taken.add(local);
      typeLocals.set(key, local);
      addImport(specifier, type.name === local ? local : `${type.name} as ${local}`);
    }

    return local;
  };

  // routes resolved first and their error types imported after, in a fixed
  // order, so the names the imports get do not depend on the route order
  const pending: { id: string; local: string; route: TypegenRoute; path: string; errors: ResolvedError[] }[] = [];

  for (const route of routes) {
    // `@Get('/')` under `@Controller('/users')` registers `/users/`, which the
    // router also serves as `/users`; the shorter form is the one people write.
    // A path of only slashes (`//`) is the root.
    const path = route.path.replace(/(.)\/+$/, '$1');
    const id = `${route.method.toUpperCase()} ${path}`;

    // A framework route (health probes, devtools) is not the application's to
    // type, and looking it up by class name could find an application class
    // that happens to share the name.
    if (route.internal || entries.has(id) || pending.some((entry) => entry.id === id)) {
      continue;
    }

    const source = lookupController(controllers, route.controller, names);

    if (!source?.exportName) {
      skipped.push({ id, reason: whyNotImportable(route.controller, source, outFile) });
      continue;
    }

    const specifier = toSpecifier(outFile, source.file);

    files.add(source.file);
    const local = locals.get(route.controller)!;
    const binding = source.exportName === local ? local : `${source.exportName} as ${local}`;

    addImport(specifier, binding);

    pending.push({
      id,
      local,
      route,
      path,
      errors: resolveThrows(route, source, (message) => warnings.add(`${id}: ${message}`)),
    });
  }

  const errorTypes = pending.flatMap((entry) => entry.errors.flatMap((error) => (error.type ? [error] : [])));
  const typeKey = (error: ResolvedError): string => `${error.type!.module}\0${error.type!.name}\0${error.className}`;

  for (const error of errorTypes.sort((a, b) => typeKey(a).localeCompare(typeKey(b)))) {
    importType(error.type!, error.className);
  }

  for (const { id, local, route, path, errors } of pending) {
    const throws = new Map<number, string[]>();

    for (const error of errors) {
      const type = error.type ? importType(error.type, error.className) : UNKNOWN_ERROR;
      const types = throws.get(error.status) ?? [];

      if (!types.includes(type)) {
        types.push(type);
      }

      throws.set(error.status, types);
    }

    entries.set(id, `RouteDef<${local}, ${quote(route.handler)}${describeArgs(route.args, path, route.sse, throws)}>`);
  }

  // the blank line keeps formatters from treating the header as an import's comment
  const lines = [TYPEGEN_HEADER, '', `import type { RouteDef } from ${quote(clientModule)};`];

  for (const specifier of [...imports.keys()].sort()) {
    const bindings = [...imports.get(specifier)!].sort();
    const defaults = bindings.filter((b) => b.startsWith('default as '));
    const named = bindings.filter((b) => !b.startsWith('default as '));

    // `import type X from` only binds a default; a named list cannot hold one
    for (const binding of defaults) {
      lines.push(`import type ${binding.slice('default as '.length)} from ${quote(specifier)};`);
    }

    if (named.length > 0) {
      lines.push(`import type { ${named.join(', ')} } from ${quote(specifier)};`);
    }
  }

  lines.push('', 'export interface VercubeRoutes {');

  for (const id of [...entries.keys()].sort()) {
    lines.push(`  ${quote(id)}: ${entries.get(id)};`);
  }

  lines.push('}', '');

  return { code: lines.join('\n'), skipped, files: [...files].sort(), warnings: [...warnings].sort() };
}

/**
 * Finds every `@Controller()` class in the given files, or under a directory.
 *
 * @param input - A project root to scan, or the files to read
 * @returns Class name to source; `null` for a name declared in several files
 */
export async function findControllers(input: string | string[]): Promise<Record<string, ControllerSource | null>> {
  const files =
    typeof input === 'string' ? await glob(GLOB_SCAN_PATTERN, { cwd: input, absolute: true, ignore: IGNORE, dot: false }) : input;
  const found: Record<string, ControllerSource | null> = Object.create(null);

  // discovery lists a file once per class in it
  for (const file of [...new Set(files)].sort()) {
    const code = readFileSync(file, 'utf8');

    // cheap filter: parsing every file of a project takes far longer
    if (!CONTROLLER_CALL.test(code)) {
      continue;
    }

    const { controllers, types } = extractControllerExports(file, code);

    for (const [name, exportName] of controllers) {
      found[name] = name in found ? null : { file, exportName, types };
    }
  }

  return found;
}

/**
 * The source of a controller by its runtime name. A bundler renames a class
 * that collides with another (`UserController$1`); that name falls back to
 * `UserController` only when no route belongs to a class of that exact name,
 * since otherwise the two cannot be told apart.
 *
 * @param controllers - Class name to source
 * @param name - The controller's name in the route table
 * @param names - Every controller name in the route table
 * @returns The source, `null` when ambiguous, `undefined` when unknown
 */
function lookupController(
  controllers: Record<string, ControllerSource | null>,
  name: string,
  names: Set<string>,
): ControllerSource | null | undefined {
  if (name in controllers) {
    return controllers[name];
  }

  const original = name.replace(/\$\d+$/, '');

  return original !== name && !names.has(original) ? controllers[original] : undefined;
}

/**
 * Finds the source of every controller the routes name. Files listed by a
 * discovery manifest are read first; a controller missing from it (bound in
 * `setup`, say) is looked for in the rest of the project.
 *
 * @param routes - The routes
 * @param root - Project root
 * @param discovery - The discovery manifest, when the build wrote one
 * @returns Class name to source, as {@link findControllers} returns it
 */
export async function resolveControllers(
  routes: TypegenRoute[],
  root: string,
  discovery?: { root?: string; controllers?: { name: string; path: string }[] } | null,
): Promise<Record<string, ControllerSource | null>> {
  if (!discovery?.controllers?.length) {
    return findControllers(root);
  }

  // a file the manifest lists can be gone by now; the scan below finds where it went
  const listed = discovery.controllers.map((c) => resolve(discovery.root ?? root, c.path)).filter((file) => existsSync(file));
  const known = await findControllers(listed);
  const names = new Set(routes.map((route) => route.controller));
  const missing = routes.some((route) => lookupController(known, route.controller, names) === undefined);

  return missing ? { ...(await findControllers(root)), ...known } : known;
}

/**
 * Writes a generated file, leaving it alone when the content is the same, so
 * watchers and `git status` stay quiet.
 *
 * @param file - Absolute path
 * @param code - The content
 * @returns True when the file was written
 */
export function writeRouteTypes(file: string, code: string): boolean {
  if (existsSync(file) && readFileSync(file, 'utf8') === code) {
    return false;
  }

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, code, 'utf8');

  return true;
}

/** How long an application may take to boot for typegen before it is given up on. */
export const INSPECT_TIMEOUT = 60_000;

/** Where the route map goes unless configured otherwise, relative to the root. */
export const DEFAULT_TYPEGEN_OUTPUT = '.vercube/routes.d.ts';

/** The `typegen` option, as `vercube.config.ts` and the Vite plugin take it. */
export type TypegenSetting = boolean | { output?: string } | undefined;

/** The discovery manifest, as far as typegen reads it. */
export interface TypegenDiscovery {
  root?: string;
  controllers?: { name: string; path: string }[];
}

/** Options for {@link createRouteTypesWriter}. */
export interface RouteTypesWriterOptions {
  /** Project root, scanned for controllers when there is no discovery manifest. */
  root: string;
  /** Absolute path of the route map. */
  outFile: string;
  /** Receives one warning per reason routes were skipped for, and a note when the file is written. */
  logger?: ScanLogger & { success?(message: string): void };
}

/** What one write did. */
export interface RouteTypesWrite {
  /** Absolute path of the route map. */
  file: string;
  /** False when the content was already up to date. */
  written: boolean;
  /** Number of route registrations read. */
  routes: number;
  /** Routes left out, with the reason. */
  skipped: { id: string; reason: string }[];
  /** Controller files the route map imports. */
  files: string[];
}

/**
 * Where the route map should be written: wherever `setting` says when it is
 * set, otherwise only for projects that depend on `@vercube/client`, so nobody
 * gets a file that imports a package they do not have.
 *
 * @param root - Project root
 * @param setting - The `typegen` option
 * @param force - Ignore whether the project depends on `@vercube/client`; `false` still wins
 * @returns Absolute path, or `null` when typegen is off
 */
export function resolveTypegenOutput(root: string, setting: TypegenSetting, force = false): string | null {
  if (setting === false) {
    return null;
  }

  if (setting === undefined && !force && !dependsOnClient(root)) {
    return null;
  }

  return resolve(root, (typeof setting === 'object' ? setting.output : undefined) ?? DEFAULT_TYPEGEN_OUTPUT);
}

/**
 * Returns a function that keeps the route map in step with a routes section.
 *
 * The map only depends on the route table and on where the controllers live,
 * so a call whose route table matches the previous one, with every imported
 * file still in place, generates nothing. A dev server can therefore call it
 * on every reload. Controller files come from the discovery manifest when
 * there is one, and from scanning the root otherwise.
 *
 * @param options - Root, output path and logger
 * @returns The writer; calls are not meant to overlap
 */
export function createRouteTypesWriter(
  options: RouteTypesWriterOptions,
): (routes: TypegenRoute[], discovery?: TypegenDiscovery | null) => Promise<RouteTypesWrite> {
  const { root, outFile, logger } = options;
  let warned: string | undefined;
  let warnedTypes = new Set<string>();

  // Controllers are looked up on every report rather than cached by route
  // table: a controller can move, gain an export or stop being ambiguous
  // without any route changing, and the map must follow. The file is only
  // written when its content changes, and also when it was deleted.
  return async (routes, discovery) => {
    const controllers = await resolveControllers(routes, root, discovery);
    const result = generateRouteTypes({ routes, controllers, outFile });
    const written = writeRouteTypes(outFile, result.code);
    const skipped = JSON.stringify(result.skipped);

    // the same warnings on every save would bury everything else
    if (skipped !== warned) {
      // grouped by reason: a library controller (devtools, say) has dozens of routes
      const byReason = Map.groupBy(result.skipped, (entry) => entry.reason);

      for (const [reason, entries] of byReason) {
        const more = entries.length > 1 ? ` and ${entries.length - 1} more route${entries.length > 2 ? 's' : ''}` : '';

        logger?.warn(`Skipped ${entries[0].id}${more}: ${reason}`);
      }

      warned = skipped;
    }

    // each problem once, not again on every save
    for (const warning of result.warnings) {
      if (!warnedTypes.has(warning)) {
        logger?.warn(warning);
      }
    }

    warnedTypes = new Set(result.warnings);

    if (written) {
      logger?.success?.(`Route types written to ${outFile}`);
    }

    return { file: outFile, written, routes: routes.length, skipped: result.skipped, files: result.files };
  };
}

/**
 * Runs a built Vercube entry with introspection on and returns the sections.
 *
 * The entry is the only thing that knows what the application's `setup` binds,
 * so it is run, and core stops it right before it would bind a port. Its stdout
 * goes to this process's stderr: an application may log while it boots, and
 * none of that belongs in the result.
 *
 * @param file - The built entry
 * @param sections - Section ids; every section when empty
 * @param cwd - Working directory, where the discovery manifest is looked up
 * @param timeout - Milliseconds before the run is stopped and the call rejects; 0 waits forever
 * @returns Section id to section
 */
export async function inspectEntry(
  file: string,
  sections: string[] = [],
  cwd: string = process.cwd(),
  timeout = 0,
): Promise<Record<string, { id: string; title: string; revision: number; data: unknown }>> {
  const directory = mkdtempSync(join(tmpdir(), 'vercube-inspect-'));
  const output = join(directory, 'introspection.json');

  try {
    await new Promise<void>((done, fail) => {
      const child = spawn(process.execPath, [file], {
        cwd,
        env: {
          ...process.env,
          // an entry that only calls `listen()` when it should listen (an app
          // that serves a frontend, or one built on a serverless platform)
          // must still reach it, where core stops before binding the port
          VERCUBE_LISTEN: '1',
          VERCUBE_INSPECT: sections.length > 0 ? sections.join(',') : '*',
          VERCUBE_INSPECT_OUT: output,
        },
        // piped rather than handed over: in a worker thread `process.stderr`
        // has no file descriptor to give
        stdio: ['ignore', 'pipe', 'pipe', 'ipc'],
      });
      let finished = false;
      const finish = (error?: Error): void => {
        if (finished) {
          return;
        }

        finished = true;
        clearTimeout(timer);

        if (error) {
          fail(error);
        } else {
          done();
        }
      };

      child.stdout!.pipe(process.stderr, { end: false });
      child.stderr!.pipe(process.stderr, { end: false });

      // an application whose setup waits on a service that never answers
      const timer =
        timeout > 0
          ? setTimeout(() => {
              child.kill('SIGKILL');
              finish(new Error(`Inspect did not finish within ${timeout / 1000}s`));
            }, timeout)
          : undefined;

      // core says so once the file is written: a setup that leaves a handle
      // open (a database pool, say) would otherwise keep the process alive
      child.on('message', (message: { type?: string }) => {
        if (message?.type === 'vercube:inspected') {
          child.kill('SIGKILL');
          finish();
        }
      });
      child.on('error', finish);
      child.on('exit', (code) => {
        if (code === 0) {
          finish();
        } else {
          finish(new Error(`Inspect exited with code ${code}`));
        }
      });
    });

    return JSON.parse(readFileSync(output, 'utf8'));
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

/**
 * @param root - Project root
 * @returns True when its `package.json` lists `@vercube/client`
 */
function dependsOnClient(root: string): boolean {
  try {
    const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')) as Record<
      string,
      Record<string, string> | undefined
    >;

    return ['dependencies', 'devDependencies', 'peerDependencies'].some((key) => Boolean(pkg[key]?.['@vercube/client']));
  } catch {
    return false;
  }
}

/**
 * @param name - Controller class name
 * @param source - What the scan found for it
 * @param outFile - The generated file, for a readable relative path
 * @returns Why a route on this controller cannot be typed
 */
function whyNotImportable(name: string, source: ControllerSource | null | undefined, outFile: string): string {
  if (source === undefined) {
    return `no source file found for ${name}`;
  }

  if (source === null) {
    return `${name} is declared in more than one file`;
  }

  return `${name} is not exported from ${relative(dirname(outFile), source.file)}`;
}

/**
 * @param file - File name, for the parser to pick the syntax
 * @param code - Its source
 * @returns Controller class name to the name it is exported under (`null` when
 *   it is not), and the classes the file can name ({@link ControllerSource.types})
 */
function extractControllerExports(
  file: string,
  code: string,
): { controllers: Map<string, string | null>; types: Record<string, TypegenImport | null> } {
  const program = parseSync(file, code).program as { body: any[] };
  const controllers = new Map<string, string | null>();
  const { names, namespaces } = controllerBindings(program.body);
  const isControllerCall = (expression: any): boolean => {
    const callee = expression?.type === 'CallExpression' ? expression.callee : null;

    return (
      (callee?.type === 'Identifier' && names.has(callee.name)) ||
      (callee?.type === 'MemberExpression' && callee.property?.name === 'Controller' && namespaces.has(callee.object?.name))
    );
  };
  const isController = (node: any): boolean =>
    (node?.type === 'ClassDeclaration' || node?.type === 'Class') &&
    Boolean(node.id?.name) &&
    (node.decorators ?? []).some((decorator: any) => isControllerCall(decorator.expression));

  for (const node of program.body) {
    if (node.type === 'ExportNamedDeclaration' && isController(node.declaration)) {
      controllers.set(node.declaration.id.name, node.declaration.id.name);
    } else if (node.type === 'ExportDefaultDeclaration' && isController(node.declaration)) {
      controllers.set(node.declaration.id.name, 'default');
    } else if (isController(node)) {
      controllers.set(node.id.name, null);
    }
  }

  // `export { UserController }`, `export { A as B }`, `export default UserController`
  for (const node of program.body) {
    if (node.type === 'ExportNamedDeclaration' && !node.source) {
      for (const specifier of node.specifiers ?? []) {
        const local = specifier.local?.name;

        if (controllers.get(local) === null) {
          controllers.set(local, specifier.exported?.name ?? specifier.exported?.value ?? local);
        }
      }
    } else if (
      node.type === 'ExportDefaultDeclaration' &&
      node.declaration?.type === 'Identifier' &&
      controllers.get(node.declaration.name) === null
    ) {
      controllers.set(node.declaration.name, 'default');
    }
  }

  return { controllers, types: namedTypes(file, program) };
}

/**
 * The classes a file can name and where to import each from: its imports, by
 * the imported name (a class keeps its own name at runtime, whatever the local
 * alias), members of its namespace imports, and its own classes.
 *
 * @param file - Absolute path of the file
 * @param program - The parsed file
 * @returns Class name to import, `null` for a name that cannot be imported
 */
function namedTypes(file: string, program: any): Record<string, TypegenImport | null> {
  const body: any[] = program.body;
  const types: Record<string, TypegenImport | null> = Object.create(null);
  const set = (name: string, type: TypegenImport | null): void => {
    if (!Object.hasOwn(types, name)) {
      types[name] = type;
      return;
    }

    const existing = types[name];

    // two different classes going by one name cannot be told apart
    if (!existing || !type || existing.module !== type.module || existing.name !== type.name) {
      types[name] = null;
    }
  };

  // the file's own classes, and the name each is exported under
  const declared = new Set<string>();
  const exported = new Map<string, string>();

  for (const node of body) {
    const declaration =
      node.type === 'ExportNamedDeclaration' || node.type === 'ExportDefaultDeclaration' ? node.declaration : node;

    if (isClass(declaration) && declaration.id?.name) {
      declared.add(declaration.id.name);

      if (node.type === 'ExportNamedDeclaration') {
        exported.set(declaration.id.name, declaration.id.name);
      } else if (node.type === 'ExportDefaultDeclaration') {
        exported.set(declaration.id.name, 'default');
      }
    } else if (node.type === 'ExportNamedDeclaration' && !node.source) {
      for (const specifier of node.specifiers ?? []) {
        const name = specifier.exported?.name ?? specifier.exported?.value;

        if (!exported.has(specifier.local?.name)) {
          exported.set(specifier.local?.name, name);
        }
      }
    } else if (
      // `export default ConflictError`
      node.type === 'ExportDefaultDeclaration' &&
      node.declaration?.type === 'Identifier' &&
      !exported.has(node.declaration.name)
    ) {
      exported.set(node.declaration.name, 'default');
    }
  }

  for (const name of declared) {
    set(name, exported.has(name) ? { module: file, name: exported.get(name)! } : null);
  }

  const namespaces = new Map<string, string>();

  for (const node of body) {
    if (node.type !== 'ImportDeclaration' || node.importKind === 'type') {
      continue;
    }

    const module = resolveModule(file, node.source.value);

    for (const specifier of node.specifiers ?? []) {
      if (specifier.importKind === 'type') {
        continue;
      }

      const imported = specifier.type === 'ImportSpecifier' ? (specifier.imported?.name ?? specifier.imported?.value) : undefined;

      if (!module) {
        // a relative import that does not resolve: its names are known, not importable,
        // so a custom `NotFoundError` from it is never mistaken for the core one
        set(imported === undefined || imported === 'default' ? specifier.local.name : imported, null);
        continue;
      }

      if (specifier.type === 'ImportSpecifier' && imported !== 'default') {
        set(imported, { module, name: imported });
      } else if (specifier.type === 'ImportDefaultSpecifier' || specifier.type === 'ImportSpecifier') {
        // `import X from` and `import { default as X } from`
        // the class keeps its declared name at runtime, whatever this file calls it
        set(defaultClassName(module) ?? specifier.local.name, { module, name: 'default' });
      } else if (specifier.type === 'ImportNamespaceSpecifier') {
        namespaces.set(specifier.local.name, module);
      }
    }
  }

  // `@Throws(Errors.ConflictError)` through `import * as Errors`
  if (namespaces.size > 0) {
    walk(program, (node) => {
      if (
        node.type === 'MemberExpression' &&
        !node.computed &&
        node.object?.type === 'Identifier' &&
        namespaces.has(node.object.name) &&
        node.property?.type === 'Identifier'
      ) {
        set(node.property.name, { module: namespaces.get(node.object.name)!, name: node.property.name });
      }
    });
  }

  return types;
}

/**
 * @param node - Any AST node
 * @returns True for a class declaration or expression
 */
function isClass(node: any): boolean {
  return node?.type === 'ClassDeclaration' || node?.type === 'Class' || node?.type === 'ClassExpression';
}

/**
 * Calls `visit` for every node below `node`.
 *
 * @param node - The root
 * @param visit - Called with each node
 */
function walk(node: any, visit: (node: any) => void): void {
  if (!node || typeof node !== 'object') {
    return;
  }

  if (Array.isArray(node)) {
    for (const child of node) {
      walk(child, visit);
    }

    return;
  }

  if (typeof node.type === 'string') {
    visit(node);
  }

  for (const key in node) {
    if (key !== 'parent') {
      walk(node[key], visit);
    }
  }
}

/**
 * The name of the class a file exports as default, read from its source.
 *
 * @param module - A package name, or an absolute file path
 * @returns The class name, `undefined` for a package or a file without one
 */
function defaultClassName(module: string): string | undefined {
  if (!isAbsolute(module)) {
    return undefined;
  }

  try {
    const body: any[] = (parseSync(module, readFileSync(module, 'utf8')).program as { body: any[] }).body;
    const node = body.find((statement) => statement.type === 'ExportDefaultDeclaration');

    if (isClass(node?.declaration)) {
      return node.declaration.id?.name;
    }

    if (node?.declaration?.type === 'Identifier') {
      const name = node.declaration.name;

      return body.some((statement) => isClass(statement) && statement.id?.name === name) ? name : undefined;
    }
  } catch {
    // unreadable or not parseable: the import's local name is used instead
  }

  return undefined;
}

/** Extensions tried, in order, for a relative import written without one. */
const SOURCE_EXTENSIONS = ['.ts', '.tsx', '.mts', '.cts', '.js', '.mjs', '/index.ts', '/index.js'];

/**
 * Where an import points: the package name as it is, a relative path as the
 * absolute file it resolves to.
 *
 * @param from - The importing file
 * @param specifier - The import source
 * @returns The module, `null` for a relative path that does not resolve
 */
function resolveModule(from: string, specifier: string): string | null {
  if (!specifier.startsWith('.')) {
    return specifier;
  }

  const base = resolve(dirname(from), specifier);
  // `./Errors.js` in TypeScript source names `./Errors.ts`
  const stem = base.replace(/\.(?:m|c)?js$/, '');
  const candidates = [base, ...SOURCE_EXTENSIONS.map((ext) => stem + ext)];

  // a directory is not a module: its `index` file is
  return candidates.find((candidate) => existsSync(candidate) && statSync(candidate).isFile()) ?? null;
}

/** An error of a route, with the type to import, `null` when it cannot be imported. */
interface ResolvedError {
  status: number;
  type: TypegenImport | null;
  /** The runtime class name, which a default import goes by. */
  className: string;
}

/**
 * The errors of one route. An implicit error names its module; a declared one
 * is imported from wherever the controller file imports it, and from
 * `@vercube/core` only when the file does not know the name at all.
 *
 * @param route - The route
 * @param source - Its controller's source
 * @param warn - Reports an error that could not be imported
 * @returns The errors, in the order the route table lists them
 */
function resolveThrows(route: TypegenRoute, source: ControllerSource, warn: (message: string) => void): ResolvedError[] {
  const known = (name: string): TypegenImport | null | undefined =>
    source.types && Object.hasOwn(source.types, name) ? source.types[name] : undefined;

  return (route.throws ?? []).map(({ name, status, module }) => {
    // a bundler renames a class that collides with another
    const original = name.replace(/\$\d+$/, '');
    let type: TypegenImport | null | undefined = module ? { module, name: original } : known(name);

    if (type === undefined) {
      type = known(original);
    }

    if (type === undefined && CORE_ERRORS.has(original)) {
      type = { module: '@vercube/core', name: original };
    }

    if (!type) {
      warn(
        type === null
          ? `cannot import the type of ${original} (${status}): the controller's file declares it without exporting it, ` +
              `or imports two classes of that name. It is typed as a generic error.`
          : `cannot import the type of ${original} (${status}), so it is typed as a generic error. ` +
              `Import it in the controller's file, or export it from there.`,
      );
    }

    return { status, type: type ?? null, className: original };
  });
}

/**
 * How a file refers to `@Controller`: its own name, an alias
 * (`import { Controller as HttpController }`) or a namespace (`core.Controller`).
 *
 * @param body - The file's top-level statements
 * @returns Local names of the decorator, and namespaces it can be reached through
 */
function controllerBindings(body: any[]): { names: Set<string>; namespaces: Set<string> } {
  const names = new Set(['Controller']);
  const namespaces = new Set<string>();

  for (const node of body) {
    if (node.type !== 'ImportDeclaration') {
      continue;
    }

    for (const specifier of node.specifiers ?? []) {
      const imported = specifier.imported?.name ?? specifier.imported?.value;

      if (specifier.type === 'ImportSpecifier' && imported === 'Controller') {
        names.add(specifier.local.name);
      } else if (specifier.type === 'ImportNamespaceSpecifier') {
        namespaces.add(specifier.local.name);
      }
    }
  }

  return { names, namespaces };
}

/**
 * @param args - The handler's arguments
 * @param path - The route template
 * @param sse - Whether it is an `@Sse()` route
 * @param throws - Error types by status
 * @returns `, { ... }` with every argument index the client needs, or nothing
 */
function describeArgs(
  args: TypegenRoute['args'],
  path: string,
  sse: boolean | undefined,
  throws: Map<number, string[]> = new Map(),
): string {
  const param: Record<string, number | null> = {};
  const query: Record<string, number> = {};
  const header: Record<string, number> = {};
  const parts: string[] = [];
  let queries: number | undefined;
  let body: number | undefined;
  let form: number | undefined;

  for (const [, name] of path.matchAll(SEGMENT)) {
    param[name] = null;
  }

  for (const arg of args) {
    if (arg.type === 'param' && arg.name && arg.name in param) {
      param[arg.name] = arg.idx;
    } else if (arg.type === 'query-param' && arg.name) {
      query[arg.name] = arg.idx;
    } else if (arg.type === 'query-params') {
      queries = arg.idx;
    } else if (arg.type === 'header' && arg.name) {
      header[arg.name] = arg.idx;
    } else if (arg.type === 'body') {
      body = arg.idx;
    } else if (arg.type === 'multipart-form-data') {
      form = arg.idx;
    }
  }

  const record = (key: string, values: Record<string, number | null>): void => {
    const keys = Object.keys(values).sort();

    if (keys.length > 0) {
      parts.push(`${key}: { ${keys.map((k) => `${quoteKey(k)}: ${values[k]}`).join('; ')} }`);
    }
  };

  record('param', param);
  record('query', query);

  if (queries !== undefined) {
    parts.push(`queries: ${queries}`);
  }

  record('header', header);

  if (body !== undefined) {
    parts.push(`body: ${body}`);
  }

  if (form !== undefined) {
    parts.push(`form: ${form}`);
  }

  if (sse) {
    parts.push('sse: true');
  }

  if (throws.size > 0) {
    const statuses = [...throws.keys()].sort((a, b) => a - b);

    parts.push(`throws: { ${statuses.map((status) => `${status}: ${[...throws.get(status)!].sort().join(' | ')}`).join('; ')} }`);
  }

  return parts.length > 0 ? `, { ${parts.join('; ')} }` : '';
}

/**
 * @param from - The generated file
 * @param to - The controller's source
 * @returns A relative module specifier, with the extension of the emitted JavaScript
 */
function toSpecifier(from: string, to: string): string {
  const path = relative(dirname(from), to)
    // `.js` resolves to the `.ts` source under every module resolution,
    // extensionless only under `bundler`
    .replace(/\.(?:ts|tsx)$/, '.js')
    .replace(/\.mts$/, '.mjs')
    .replace(/\.cts$/, '.cjs');

  // `.hidden/X.js` would be a package name, not a relative path
  return path.startsWith('./') || path.startsWith('../') ? path : `./${path}`;
}

/**
 * @param value - Any string
 * @returns It as a single-quoted literal
 */
function quote(value: string): string {
  return `'${value.replaceAll('\\', String.raw`\\`).replaceAll("'", String.raw`\'`)}'`;
}

/**
 * @param key - A property name
 * @returns It bare when it is an identifier, quoted otherwise
 */
function quoteKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : quote(key);
}
