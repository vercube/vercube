import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { parseSync } from 'oxc-parser';
import { dirname, relative } from 'pathe';
import { glob } from 'tinyglobby';
import { extractDecoratorArg } from './Ast';
import { GLOB_SCAN_PATTERN } from './Scan';

/**
 * One route as the `routes` introspection section describes it. Declared here
 * structurally so the scanner does not depend on `@vercube/core`.
 */
export interface TypegenRoute {
  method: string;
  path: string;
  controller: string;
  handler: string;
  args: { idx: number; type: string; name?: string }[];
  sse?: boolean;
}

/** Where a controller class lives and how it is exported. */
export interface ControllerSource {
  /** Absolute path of the file. */
  file: string;
  /** The exported name, `default` for a default export, `null` when the class is not exported. */
  exportName: string | null;
}

/** Options for {@link generateRouteTypes}. */
export interface TypegenOptions {
  /** The routes to describe. */
  routes: TypegenRoute[];
  /**
   * Controller class name to its source. `null` marks a name declared in more
   * than one file, which cannot be told apart by name.
   */
  controllers: Record<string, ControllerSource | null>;
  /** Absolute path of the file the result is written to; imports are relative to it. */
  outFile: string;
  /** Module `RouteDef` is imported from. */
  clientModule?: string;
}

/** What {@link generateRouteTypes} produced. */
export interface TypegenResult {
  /** The declaration file. */
  code: string;
  /** Routes left out, with the reason, one per route id. */
  skipped: { id: string; reason: string }[];
}

/** First line of every generated file, also how a generated file is recognised. */
export const TYPEGEN_HEADER = '// Generated by Vercube from your controllers. Do not edit: `vercube typegen` rewrites it.';

/** Files never worth parsing for controllers. */
const IGNORE = [
  '**/node_modules/**',
  '**/dist/**',
  '**/.output/**',
  '**/.vercube/**',
  '**/.nitro/**',
  '**/coverage/**',
  '**/*.d.ts',
  '**/*.{test,spec}.*',
  '**/{test,tests,__tests__}/**',
];

/** `:name` and `**:name` segments of a route template. */
const SEGMENT = /(?:\*\*)?:(\w+)/g;

/**
 * Writes the type references `@vercube/client` turns into a typed route map.
 *
 * Nothing about the routes' types is printed: each entry names the controller
 * class, the handler and the argument index of each parameter decorator, and
 * `RouteDef` asks the compiler for the rest. Output is sorted, so the same
 * application always produces the same file.
 *
 * Routes whose controller cannot be imported (unknown file, not exported, the
 * class name declared twice) are left out and reported in `skipped`.
 *
 * @param options - Routes, controller sources and the output path
 * @returns The file and the routes it left out
 */
export function generateRouteTypes(options: TypegenOptions): TypegenResult {
  const { routes, controllers, outFile, clientModule = '@vercube/client' } = options;
  const entries = new Map<string, string>();
  const imports = new Map<string, Set<string>>();
  const skipped: TypegenResult['skipped'] = [];

  for (const route of routes) {
    // `@Get('/')` under `@Controller('/users')` registers `/users/`, which the
    // router also serves as `/users`; the shorter form is the one people write
    const path = route.path.length > 1 ? route.path.replace(/\/+$/, '') : route.path;
    const id = `${route.method.toUpperCase()} ${path}`;

    if (entries.has(id)) {
      continue;
    }

    const source = controllers[route.controller];

    if (!source?.exportName) {
      skipped.push({ id, reason: whyNotImportable(route.controller, source, outFile) });
      continue;
    }

    const specifier = toSpecifier(outFile, source.file);
    const binding = source.exportName === route.controller ? route.controller : `${source.exportName} as ${route.controller}`;

    if (!imports.has(specifier)) {
      imports.set(specifier, new Set());
    }

    imports.get(specifier)!.add(binding);
    entries.set(id, `RouteDef<${route.controller}, ${quote(route.handler)}${describeArgs(route.args, path, route.sse)}>`);
  }

  const lines = [TYPEGEN_HEADER, `import type { RouteDef } from ${quote(clientModule)};`];

  for (const specifier of [...imports.keys()].sort()) {
    const bindings = [...imports.get(specifier)!].sort();
    const defaults = bindings.filter((b) => b.startsWith('default as '));
    const named = bindings.filter((b) => !b.startsWith('default as '));

    // `import type X from` only binds a default; a named list cannot hold one
    for (const binding of defaults) {
      lines.push(`import type ${binding.slice('default as '.length)} from ${quote(specifier)};`);
    }

    if (named.length > 0) {
      lines.push(`import type { ${named.join(', ')} } from ${quote(specifier)};`);
    }
  }

  lines.push('', 'export interface VercubeRoutes {');

  for (const id of [...entries.keys()].sort()) {
    lines.push(`  ${quote(id)}: ${entries.get(id)};`);
  }

  lines.push('}', '');

  return { code: lines.join('\n'), skipped };
}

/**
 * Finds every `@Controller()` class in the given files, or under a directory.
 *
 * @param input - A project root to scan, or the files to read
 * @returns Class name to source; `null` for a name declared in several files
 */
export async function findControllers(input: string | string[]): Promise<Record<string, ControllerSource | null>> {
  const files =
    typeof input === 'string' ? await glob(GLOB_SCAN_PATTERN, { cwd: input, absolute: true, ignore: IGNORE, dot: false }) : input;
  const found: Record<string, ControllerSource | null> = {};

  for (const file of files.sort()) {
    const code = readFileSync(file, 'utf8');

    // cheap filter: parsing every file of a project takes far longer
    if (!code.includes('Controller(')) {
      continue;
    }

    for (const [name, exportName] of extractControllerExports(file, code)) {
      found[name] = name in found ? null : { file, exportName };
    }
  }

  return found;
}

/**
 * Writes a generated file, leaving it alone when the content is the same, so
 * watchers and `git status` stay quiet.
 *
 * @param file - Absolute path
 * @param code - The content
 * @returns True when the file was written
 */
export function writeRouteTypes(file: string, code: string): boolean {
  if (existsSync(file) && readFileSync(file, 'utf8') === code) {
    return false;
  }

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, code, 'utf8');

  return true;
}

/**
 * @param name - Controller class name
 * @param source - What the scan found for it
 * @param outFile - The generated file, for a readable relative path
 * @returns Why a route on this controller cannot be typed
 */
function whyNotImportable(name: string, source: ControllerSource | null | undefined, outFile: string): string {
  if (source === undefined) {
    return `no source file found for ${name}`;
  }

  if (source === null) {
    return `${name} is declared in more than one file`;
  }

  return `${name} is not exported from ${relative(dirname(outFile), source.file)}`;
}

/**
 * @param file - File name, for the parser to pick the syntax
 * @param code - Its source
 * @returns Controller class name to the name it is exported under (`null` when it is not)
 */
function extractControllerExports(file: string, code: string): Map<string, string | null> {
  const program = parseSync(file, code).program as { body: any[] };
  const controllers = new Map<string, string | null>();
  const isController = (node: any): boolean =>
    (node?.type === 'ClassDeclaration' || node?.type === 'Class') &&
    Boolean(node.id?.name) &&
    extractDecoratorArg(node.decorators, 'Controller') !== null;

  for (const node of program.body) {
    if (node.type === 'ExportNamedDeclaration' && isController(node.declaration)) {
      controllers.set(node.declaration.id.name, node.declaration.id.name);
    } else if (node.type === 'ExportDefaultDeclaration' && isController(node.declaration)) {
      controllers.set(node.declaration.id.name, 'default');
    } else if (isController(node)) {
      controllers.set(node.id.name, null);
    }
  }

  // `export { UserController }`, `export { A as B }`, `export default UserController`
  for (const node of program.body) {
    if (node.type === 'ExportNamedDeclaration' && !node.source) {
      for (const specifier of node.specifiers ?? []) {
        const local = specifier.local?.name;

        if (controllers.get(local) === null) {
          controllers.set(local, specifier.exported?.name ?? specifier.exported?.value ?? local);
        }
      }
    } else if (
      node.type === 'ExportDefaultDeclaration' &&
      node.declaration?.type === 'Identifier' &&
      controllers.get(node.declaration.name) === null
    ) {
      controllers.set(node.declaration.name, 'default');
    }
  }

  return controllers;
}

/**
 * @param args - The handler's arguments
 * @param path - The route template
 * @param sse - Whether it is an `@Sse()` route
 * @returns `, { ... }` with every argument index the client needs, or nothing
 */
function describeArgs(args: TypegenRoute['args'], path: string, sse: boolean | undefined): string {
  const param: Record<string, number | null> = {};
  const query: Record<string, number> = {};
  const header: Record<string, number> = {};
  const parts: string[] = [];
  let queries: number | undefined;
  let body: number | undefined;
  let form: number | undefined;

  for (const [, name] of path.matchAll(SEGMENT)) {
    param[name] = null;
  }

  for (const arg of args) {
    if (arg.type === 'param' && arg.name && arg.name in param) {
      param[arg.name] = arg.idx;
    } else if (arg.type === 'query-param' && arg.name) {
      query[arg.name] = arg.idx;
    } else if (arg.type === 'query-params') {
      queries = arg.idx;
    } else if (arg.type === 'header' && arg.name) {
      header[arg.name] = arg.idx;
    } else if (arg.type === 'body') {
      body = arg.idx;
    } else if (arg.type === 'multipart-form-data') {
      form = arg.idx;
    }
  }

  const record = (key: string, values: Record<string, number | null>): void => {
    const keys = Object.keys(values).sort();

    if (keys.length > 0) {
      parts.push(`${key}: { ${keys.map((k) => `${quoteKey(k)}: ${values[k]}`).join('; ')} }`);
    }
  };

  record('param', param);
  record('query', query);

  if (queries !== undefined) {
    parts.push(`queries: ${queries}`);
  }

  record('header', header);

  if (body !== undefined) {
    parts.push(`body: ${body}`);
  }

  if (form !== undefined) {
    parts.push(`form: ${form}`);
  }

  if (sse) {
    parts.push('sse: true');
  }

  return parts.length > 0 ? `, { ${parts.join('; ')} }` : '';
}

/**
 * @param from - The generated file
 * @param to - The controller's source
 * @returns A relative module specifier, without a TypeScript extension
 */
function toSpecifier(from: string, to: string): string {
  const path = relative(dirname(from), to)
    .replace(/\.(?:ts|tsx)$/, '')
    .replace(/\.mts$/, '.mjs')
    .replace(/\.cts$/, '.cjs');

  return path.startsWith('.') ? path : `./${path}`;
}

/**
 * @param value - Any string
 * @returns It as a single-quoted literal
 */
function quote(value: string): string {
  return `'${value.replaceAll('\\', String.raw`\\`).replaceAll("'", String.raw`\'`)}'`;
}

/**
 * @param key - A property name
 * @returns It bare when it is an identifier, quoted otherwise
 */
function quoteKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : quote(key);
}
