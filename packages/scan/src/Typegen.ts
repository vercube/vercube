import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { parseSync } from 'oxc-parser';
import { dirname, join, relative, resolve } from 'pathe';
import { glob } from 'tinyglobby';
import { GLOB_SCAN_PATTERN } from './Scan';
import type { ScanLogger } from './Types';

/**
 * One route as the `routes` introspection section describes it. Declared here
 * structurally so the scanner does not depend on `@vercube/core`.
 */
export interface TypegenRoute {
  method: string;
  path: string;
  controller: string;
  handler: string;
  args: { idx: number; type: string; name?: string }[];
  sse?: boolean;
}

/** Where a controller class lives and how it is exported. */
export interface ControllerSource {
  /** Absolute path of the file. */
  file: string;
  /** The exported name, `default` for a default export, `null` when the class is not exported. */
  exportName: string | null;
}

/** Options for {@link generateRouteTypes}. */
export interface TypegenOptions {
  /** The routes to describe. */
  routes: TypegenRoute[];
  /**
   * Controller class name to its source. `null` marks a name declared in more
   * than one file, which cannot be told apart by name.
   */
  controllers: Record<string, ControllerSource | null>;
  /** Absolute path of the file the result is written to; imports are relative to it. */
  outFile: string;
  /** Module `RouteDef` is imported from. */
  clientModule?: string;
}

/** What {@link generateRouteTypes} produced. */
export interface TypegenResult {
  /** The declaration file. */
  code: string;
  /** Routes left out, with the reason, one per route id. */
  skipped: { id: string; reason: string }[];
  /** Absolute paths of the controller files the result imports. */
  files: string[];
}

/** First line of every generated file, also how a generated file is recognised. */
export const TYPEGEN_HEADER = '// Generated by Vercube from your controllers. Do not edit: `vercube typegen` rewrites it.';

/** Files never worth parsing for controllers. */
const IGNORE = [
  '**/node_modules/**',
  '**/dist/**',
  '**/.output/**',
  '**/.vercube/**',
  '**/.nitro/**',
  '**/coverage/**',
  '**/*.d.ts',
  '**/*.{test,spec}.*',
  '**/{test,tests,__tests__}/**',
];

/** Names the generated file declares itself. */
const RESERVED = new Set(['RouteDef', 'VercubeRoutes']);

/** A `Controller(` call, allowing for whitespace and an alias such as `HttpController(`. */
const CONTROLLER_CALL = /Controller\s*\(/;

/** `:name` and `**:name` segments of a route template. */
const SEGMENT = /(?:\*\*)?:(\w+)/g;

/**
 * Writes the type references `@vercube/client` turns into a typed route map.
 *
 * Nothing about the routes' types is printed: each entry names the controller
 * class, the handler and the argument index of each parameter decorator, and
 * `RouteDef` asks the compiler for the rest. Output is sorted, so the same
 * application always produces the same file.
 *
 * Routes whose controller cannot be imported (unknown file, not exported, the
 * class name declared twice) are left out and reported in `skipped`.
 *
 * @param options - Routes, controller sources and the output path
 * @returns The file and the routes it left out
 */
export function generateRouteTypes(options: TypegenOptions): TypegenResult {
  const { routes, controllers, outFile, clientModule = '@vercube/client' } = options;
  const entries = new Map<string, string>();
  const imports = new Map<string, Set<string>>();
  const files = new Set<string>();
  const skipped: TypegenResult['skipped'] = [];

  for (const route of routes) {
    // `@Get('/')` under `@Controller('/users')` registers `/users/`, which the
    // router also serves as `/users`; the shorter form is the one people write
    const path = route.path.length > 1 ? route.path.replace(/\/+$/, '') : route.path;
    const id = `${route.method.toUpperCase()} ${path}`;

    if (entries.has(id)) {
      continue;
    }

    // a bundler renames a class that collides with another (`UserController$1`)
    const source = controllers[route.controller] ?? controllers[route.controller.replace(/\$\d+$/, '')];

    if (!source?.exportName) {
      skipped.push({ id, reason: whyNotImportable(route.controller, source, outFile) });
      continue;
    }

    const specifier = toSpecifier(outFile, source.file);

    files.add(source.file);
    // the file's own names cannot be taken by a controller
    const local = RESERVED.has(route.controller) ? `${route.controller}_` : route.controller;
    const binding = source.exportName === local ? local : `${source.exportName} as ${local}`;

    if (!imports.has(specifier)) {
      imports.set(specifier, new Set());
    }

    imports.get(specifier)!.add(binding);
    entries.set(id, `RouteDef<${local}, ${quote(route.handler)}${describeArgs(route.args, path, route.sse)}>`);
  }

  const lines = [TYPEGEN_HEADER, `import type { RouteDef } from ${quote(clientModule)};`];

  for (const specifier of [...imports.keys()].sort()) {
    const bindings = [...imports.get(specifier)!].sort();
    const defaults = bindings.filter((b) => b.startsWith('default as '));
    const named = bindings.filter((b) => !b.startsWith('default as '));

    // `import type X from` only binds a default; a named list cannot hold one
    for (const binding of defaults) {
      lines.push(`import type ${binding.slice('default as '.length)} from ${quote(specifier)};`);
    }

    if (named.length > 0) {
      lines.push(`import type { ${named.join(', ')} } from ${quote(specifier)};`);
    }
  }

  lines.push('', 'export interface VercubeRoutes {');

  for (const id of [...entries.keys()].sort()) {
    lines.push(`  ${quote(id)}: ${entries.get(id)};`);
  }

  lines.push('}', '');

  return { code: lines.join('\n'), skipped, files: [...files].sort() };
}

/**
 * Finds every `@Controller()` class in the given files, or under a directory.
 *
 * @param input - A project root to scan, or the files to read
 * @returns Class name to source; `null` for a name declared in several files
 */
export async function findControllers(input: string | string[]): Promise<Record<string, ControllerSource | null>> {
  const files =
    typeof input === 'string' ? await glob(GLOB_SCAN_PATTERN, { cwd: input, absolute: true, ignore: IGNORE, dot: false }) : input;
  const found: Record<string, ControllerSource | null> = {};

  // discovery lists a file once per class in it
  for (const file of [...new Set(files)].sort()) {
    const code = readFileSync(file, 'utf8');

    // cheap filter: parsing every file of a project takes far longer
    if (!CONTROLLER_CALL.test(code)) {
      continue;
    }

    for (const [name, exportName] of extractControllerExports(file, code)) {
      found[name] = name in found ? null : { file, exportName };
    }
  }

  return found;
}

/**
 * Finds the source of every controller the routes name. Files listed by a
 * discovery manifest are read first; a controller missing from it (bound in
 * `setup`, say) is looked for in the rest of the project.
 *
 * @param routes - The routes
 * @param root - Project root
 * @param discovery - The discovery manifest, when the build wrote one
 * @returns Class name to source, as {@link findControllers} returns it
 */
export async function resolveControllers(
  routes: TypegenRoute[],
  root: string,
  discovery?: { root?: string; controllers?: { name: string; path: string }[] } | null,
): Promise<Record<string, ControllerSource | null>> {
  if (!discovery?.controllers?.length) {
    return findControllers(root);
  }

  const known = await findControllers(discovery.controllers.map((c) => resolve(discovery.root ?? root, c.path)));
  const missing = routes.some((route) => !(route.controller in known) && !(route.controller.replace(/\$\d+$/, '') in known));

  return missing ? { ...(await findControllers(root)), ...known } : known;
}

/**
 * Writes a generated file, leaving it alone when the content is the same, so
 * watchers and `git status` stay quiet.
 *
 * @param file - Absolute path
 * @param code - The content
 * @returns True when the file was written
 */
export function writeRouteTypes(file: string, code: string): boolean {
  if (existsSync(file) && readFileSync(file, 'utf8') === code) {
    return false;
  }

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, code, 'utf8');

  return true;
}

/** How long an application may take to boot for typegen before it is given up on. */
export const INSPECT_TIMEOUT = 60_000;

/** Where the route map goes unless configured otherwise, relative to the root. */
export const DEFAULT_TYPEGEN_OUTPUT = '.vercube/routes.d.ts';

/** The `typegen` option, as `vercube.config.ts` and the Vite plugin take it. */
export type TypegenSetting = boolean | { output?: string } | undefined;

/** The discovery manifest, as far as typegen reads it. */
export interface TypegenDiscovery {
  root?: string;
  controllers?: { name: string; path: string }[];
}

/** Options for {@link createRouteTypesWriter}. */
export interface RouteTypesWriterOptions {
  /** Project root, scanned for controllers when there is no discovery manifest. */
  root: string;
  /** Absolute path of the route map. */
  outFile: string;
  /** Receives one warning per skipped route, and a note when the file is written. */
  logger?: ScanLogger & { success?(message: string): void };
}

/** What one write did. */
export interface RouteTypesWrite {
  /** Absolute path of the route map. */
  file: string;
  /** False when the route table had not changed, so nothing was generated. */
  generated: boolean;
  /** False when the content was already up to date. */
  written: boolean;
  /** Number of route registrations read. */
  routes: number;
  /** Routes left out, with the reason. */
  skipped: { id: string; reason: string }[];
  /** Controller files the route map imports. */
  files: string[];
}

/**
 * Where the route map should be written: wherever `setting` says when it is
 * set, otherwise only for projects that depend on `@vercube/client`, so nobody
 * gets a file that imports a package they do not have.
 *
 * @param root - Project root
 * @param setting - The `typegen` option
 * @param force - Ignore whether the project depends on `@vercube/client`; `false` still wins
 * @returns Absolute path, or `null` when typegen is off
 */
export function resolveTypegenOutput(root: string, setting: TypegenSetting, force = false): string | null {
  if (setting === false) {
    return null;
  }

  if (setting === undefined && !force && !dependsOnClient(root)) {
    return null;
  }

  return resolve(root, (typeof setting === 'object' ? setting.output : undefined) ?? DEFAULT_TYPEGEN_OUTPUT);
}

/**
 * Returns a function that keeps the route map in step with a routes section.
 *
 * The map only depends on the route table and on where the controllers live,
 * so a call whose route table matches the previous one, with every imported
 * file still in place, generates nothing. A dev server can therefore call it
 * on every reload. Controller files come from the discovery manifest when
 * there is one, and from scanning the root otherwise.
 *
 * @param options - Root, output path and logger
 * @returns The writer; calls are not meant to overlap
 */
export function createRouteTypesWriter(
  options: RouteTypesWriterOptions,
): (routes: TypegenRoute[], discovery?: TypegenDiscovery | null) => Promise<RouteTypesWrite> {
  const { root, outFile, logger } = options;
  let key: string | undefined;
  let files: string[] = [];

  return async (routes, discovery) => {
    const next = routesKey(routes);

    if (next === key && files.every((file) => existsSync(file))) {
      return { file: outFile, generated: false, written: false, routes: routes.length, skipped: [], files };
    }

    const controllers = await resolveControllers(routes, root, discovery);
    const result = generateRouteTypes({ routes, controllers, outFile });
    const written = writeRouteTypes(outFile, result.code);

    for (const { id, reason } of result.skipped) {
      logger?.warn(`Skipped ${id}: ${reason}`);
    }

    if (written) {
      logger?.success?.(`Route types written to ${outFile}`);
    }

    key = next;
    files = result.files;

    return { file: outFile, generated: true, written, routes: routes.length, skipped: result.skipped, files };
  };
}

/**
 * Runs a built Vercube entry with introspection on and returns the sections.
 *
 * The entry is the only thing that knows what the application's `setup` binds,
 * so it is run, and core stops it right before it would bind a port. Its stdout
 * goes to this process's stderr: an application may log while it boots, and
 * none of that belongs in the result.
 *
 * @param file - The built entry
 * @param sections - Section ids; every section when empty
 * @param cwd - Working directory, where the discovery manifest is looked up
 * @param timeout - Milliseconds before the run is stopped and the call rejects; 0 waits forever
 * @returns Section id to section
 */
export async function inspectEntry(
  file: string,
  sections: string[] = [],
  cwd: string = process.cwd(),
  timeout = 0,
): Promise<Record<string, { id: string; title: string; revision: number; data: unknown }>> {
  const directory = mkdtempSync(join(tmpdir(), 'vercube-inspect-'));
  const output = join(directory, 'introspection.json');

  try {
    await new Promise<void>((done, fail) => {
      const child = spawn(process.execPath, [file], {
        cwd,
        env: {
          ...process.env,
          VERCUBE_INSPECT: sections.length > 0 ? sections.join(',') : '*',
          VERCUBE_INSPECT_OUT: output,
        },
        stdio: ['ignore', process.stderr, 'inherit'],
      });

      // an application whose setup waits on a service that never answers
      const timer =
        timeout > 0
          ? setTimeout(() => {
              child.kill('SIGKILL');
              fail(new Error(`Inspect did not finish within ${timeout / 1000}s`));
            }, timeout)
          : undefined;

      child.on('error', fail);
      child.on('exit', (code) => {
        clearTimeout(timer);

        if (code === 0) {
          done();
        } else {
          fail(new Error(`Inspect exited with code ${code}`));
        }
      });
    });

    return JSON.parse(readFileSync(output, 'utf8'));
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

/**
 * @param routes - The routes section
 * @returns Everything about it that ends up in the route map
 */
function routesKey(routes: TypegenRoute[]): string {
  return JSON.stringify(
    routes.map((route) => [
      route.method,
      route.path,
      route.controller,
      route.handler,
      route.sse,
      route.args.map((arg) => [arg.idx, arg.type, arg.name]),
    ]),
  );
}

/**
 * @param root - Project root
 * @returns True when its `package.json` lists `@vercube/client`
 */
function dependsOnClient(root: string): boolean {
  try {
    const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')) as Record<
      string,
      Record<string, string> | undefined
    >;

    return ['dependencies', 'devDependencies', 'peerDependencies'].some((key) => Boolean(pkg[key]?.['@vercube/client']));
  } catch {
    return false;
  }
}

/**
 * @param name - Controller class name
 * @param source - What the scan found for it
 * @param outFile - The generated file, for a readable relative path
 * @returns Why a route on this controller cannot be typed
 */
function whyNotImportable(name: string, source: ControllerSource | null | undefined, outFile: string): string {
  if (source === undefined) {
    return `no source file found for ${name}`;
  }

  if (source === null) {
    return `${name} is declared in more than one file`;
  }

  return `${name} is not exported from ${relative(dirname(outFile), source.file)}`;
}

/**
 * @param file - File name, for the parser to pick the syntax
 * @param code - Its source
 * @returns Controller class name to the name it is exported under (`null` when it is not)
 */
function extractControllerExports(file: string, code: string): Map<string, string | null> {
  const program = parseSync(file, code).program as { body: any[] };
  const controllers = new Map<string, string | null>();
  const { names, namespaces } = controllerBindings(program.body);
  const isControllerCall = (expression: any): boolean => {
    const callee = expression?.type === 'CallExpression' ? expression.callee : null;

    return (
      (callee?.type === 'Identifier' && names.has(callee.name)) ||
      (callee?.type === 'MemberExpression' && callee.property?.name === 'Controller' && namespaces.has(callee.object?.name))
    );
  };
  const isController = (node: any): boolean =>
    (node?.type === 'ClassDeclaration' || node?.type === 'Class') &&
    Boolean(node.id?.name) &&
    (node.decorators ?? []).some((decorator: any) => isControllerCall(decorator.expression));

  for (const node of program.body) {
    if (node.type === 'ExportNamedDeclaration' && isController(node.declaration)) {
      controllers.set(node.declaration.id.name, node.declaration.id.name);
    } else if (node.type === 'ExportDefaultDeclaration' && isController(node.declaration)) {
      controllers.set(node.declaration.id.name, 'default');
    } else if (isController(node)) {
      controllers.set(node.id.name, null);
    }
  }

  // `export { UserController }`, `export { A as B }`, `export default UserController`
  for (const node of program.body) {
    if (node.type === 'ExportNamedDeclaration' && !node.source) {
      for (const specifier of node.specifiers ?? []) {
        const local = specifier.local?.name;

        if (controllers.get(local) === null) {
          controllers.set(local, specifier.exported?.name ?? specifier.exported?.value ?? local);
        }
      }
    } else if (
      node.type === 'ExportDefaultDeclaration' &&
      node.declaration?.type === 'Identifier' &&
      controllers.get(node.declaration.name) === null
    ) {
      controllers.set(node.declaration.name, 'default');
    }
  }

  return controllers;
}

/**
 * How a file refers to `@Controller`: its own name, an alias
 * (`import { Controller as HttpController }`) or a namespace (`core.Controller`).
 *
 * @param body - The file's top-level statements
 * @returns Local names of the decorator, and namespaces it can be reached through
 */
function controllerBindings(body: any[]): { names: Set<string>; namespaces: Set<string> } {
  const names = new Set(['Controller']);
  const namespaces = new Set<string>();

  for (const node of body) {
    if (node.type !== 'ImportDeclaration') {
      continue;
    }

    for (const specifier of node.specifiers ?? []) {
      const imported = specifier.imported?.name ?? specifier.imported?.value;

      if (specifier.type === 'ImportSpecifier' && imported === 'Controller') {
        names.add(specifier.local.name);
      } else if (specifier.type === 'ImportNamespaceSpecifier') {
        namespaces.add(specifier.local.name);
      }
    }
  }

  return { names, namespaces };
}

/**
 * @param args - The handler's arguments
 * @param path - The route template
 * @param sse - Whether it is an `@Sse()` route
 * @returns `, { ... }` with every argument index the client needs, or nothing
 */
function describeArgs(args: TypegenRoute['args'], path: string, sse: boolean | undefined): string {
  const param: Record<string, number | null> = {};
  const query: Record<string, number> = {};
  const header: Record<string, number> = {};
  const parts: string[] = [];
  let queries: number | undefined;
  let body: number | undefined;
  let form: number | undefined;

  for (const [, name] of path.matchAll(SEGMENT)) {
    param[name] = null;
  }

  for (const arg of args) {
    if (arg.type === 'param' && arg.name && arg.name in param) {
      param[arg.name] = arg.idx;
    } else if (arg.type === 'query-param' && arg.name) {
      query[arg.name] = arg.idx;
    } else if (arg.type === 'query-params') {
      queries = arg.idx;
    } else if (arg.type === 'header' && arg.name) {
      header[arg.name] = arg.idx;
    } else if (arg.type === 'body') {
      body = arg.idx;
    } else if (arg.type === 'multipart-form-data') {
      form = arg.idx;
    }
  }

  const record = (key: string, values: Record<string, number | null>): void => {
    const keys = Object.keys(values).sort();

    if (keys.length > 0) {
      parts.push(`${key}: { ${keys.map((k) => `${quoteKey(k)}: ${values[k]}`).join('; ')} }`);
    }
  };

  record('param', param);
  record('query', query);

  if (queries !== undefined) {
    parts.push(`queries: ${queries}`);
  }

  record('header', header);

  if (body !== undefined) {
    parts.push(`body: ${body}`);
  }

  if (form !== undefined) {
    parts.push(`form: ${form}`);
  }

  if (sse) {
    parts.push('sse: true');
  }

  return parts.length > 0 ? `, { ${parts.join('; ')} }` : '';
}

/**
 * @param from - The generated file
 * @param to - The controller's source
 * @returns A relative module specifier, with the extension of the emitted JavaScript
 */
function toSpecifier(from: string, to: string): string {
  const path = relative(dirname(from), to)
    // `.js` resolves to the `.ts` source under every module resolution,
    // extensionless only under `bundler`
    .replace(/\.(?:ts|tsx)$/, '.js')
    .replace(/\.mts$/, '.mjs')
    .replace(/\.cts$/, '.cjs');

  return path.startsWith('.') ? path : `./${path}`;
}

/**
 * @param value - Any string
 * @returns It as a single-quoted literal
 */
function quote(value: string): string {
  return `'${value.replaceAll('\\', String.raw`\\`).replaceAll("'", String.raw`\'`)}'`;
}

/**
 * @param key - A property name
 * @returns It bare when it is an identifier, quoted otherwise
 */
function quoteKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : quote(key);
}
